export type SubsidyStatus =
  /** 申請できる */
  | "open"
  /** これから公募が開く */
  | "upcoming"
  /** 今年度は終了。来期の先回り用に残す */
  | "closed"
  /** 期日前に予算上限で止まった。再開ウォッチ対象 */
  | "suspended";

/**
 * 御社（フルスクラッチの受託開発／IT導入支援事業者の登録なし）から見た適合度。
 *   A: システム構築費が対象経費に明記されている
 *   B: 設備投資枠で乗る可能性が高い
 *   C: 限定条件つき。事務局確認が要る
 *   X: 構造的に使えない（フルスクラッチ対象外・ベンダー登録制など）
 */
